# Fire-and-forget background tasks (e.g. best-effort session persistence).
# Keep strong references until they finish, otherwise the event loop may
# garbage-collect a pending task mid-flight.
_bg_tasks: set = set()


def _schedule_bg(coro) -> None:
    task = asyncio.ensure_future(coro)
    _bg_tasks.add(task)
    task.add_done_callback(_bg_tasks.discard)


# ---------------------------------------------------------------------------
# Greeting short-circuit — shared across the three factory chats
# ---------------------------------------------------------------------------
#
# A bare greeting ("hi", "hello", "good morning", "thanks"…) sent to a factory
# chat should get a lightweight reply inviting the user to describe what they
# want — NOT trigger intent parsing, existing-match search, or a Plan Card.
# Reuses the exact same rule as regular chat (``models.classifier.GREETING_PATTERN``)
# so behaviour is consistent across all surfaces, and mirrors the Agent Builder
# greeting short-circuit: the reply is generated by the Local LLM (simple tier)
# with a canned fallback. Only fires on turn 1: a greeting mid-conversation must
# not hijack an in-progress build.

# Canned fallback used when the Local LLM greeting call fails (matches the plan
# and the Agent Builder path).
_FACTORY_GREETING_FALLBACK = "Hi! What would you like to build today?"


def _is_greeting(message: str) -> bool:
    """True when ``message`` is a bare greeting (exact match, same rule as chat).

    Multi-word inputs like "hi, build an agent that…" do NOT match (fullmatch),
    so they fall through to the normal factory flow — no regression.
    """
    try:
        from models.classifier import GREETING_PATTERN
        return bool(GREETING_PATTERN.fullmatch((message or "").strip()))
    except Exception:
        return False


# Chat phrases the confirm stage treats as an explicit "create the agent now"
# command. Matched case-insensitively against the whole trimmed message so a
# refinement message like "Actually create a tool for this" doesn't misfire.
# Reused by BOTH factories, so the optional trailing noun accepts either
# "agent" or "workflow" — "Create workflow" was silently missed otherwise.
_DEPLOY_COMMAND_PATTERNS = (
    r"^(please\s+)?(create|make|build|deploy|save|ship|apply|finalize|finalise|confirm)"
    r"(\s+(the|this|it|my))?"
    r"(\s+(agent|workflow))?"
    r"(\s+now)?\s*[.!]?$",
    r"^(go\s+ahead|do\s+it|create\s+it|deploy\s+it|save\s+it|looks\s+good[,!.\s]*(create|deploy|save).*)$",
    r"^(yes|yep|yeah|ok|okay|sure|proceed|ready)[,!.\s]*(create|deploy|save|go).*$",
    r"^i\s+am\s+ready\s+to\s+(create|deploy|save).*$",
    r"^(that'?s\s+it|we'?re\s+done|all\s+set)[,!.\s]*(create|deploy|save|go|ship).*$",
)


def _is_deploy_command(message: str) -> bool:
    """True when the user's chat message during ``confirm`` is a deploy trigger.

    Deliberately strict: multi-clause messages like "create a tool that does X"
    do NOT match (they include content after the verb). This is what makes it
    safe to short-circuit refinement — a "create agent" chat is the ONLY way
    to close the loop from the chat side; any other message is a refinement.
    """
    import re as _re
    text = (message or "").strip().lower()
    if not text or len(text) > 80:
        return False
    for pat in _DEPLOY_COMMAND_PATTERNS:
        if _re.match(pat, text):
            return True
    return False


def _greeting_reply(user_message: str) -> str:
    """Generate a greeting reply via the Local LLM (simple tier), per the plan.

    Falls back to the canned ``_FACTORY_GREETING_FALLBACK`` on any failure or
    empty output, so a greeting always returns a usable, friendly message.
    """
    try:
        from models.model_router import model_router
        answer = model_router.generate(user_message, model="simple")
    except Exception as exc:
        logger.warning(f"[AGENT] factory greeting generate failed → {exc}")
        answer = ""
    if not answer or not answer.strip():
        return _FACTORY_GREETING_FALLBACK
    return answer.strip()


# ---------------------------------------------------------------------------
# Plan Card helpers — shared across the three factories
# ---------------------------------------------------------------------------
#
# The Plan Card is a structured pre-generation questionnaire emitted on turn 1.
# The frontend sends the user's answers back as a normal chat message prefixed
# with ``__plan_card__:`` followed by a JSON object, so no new endpoint is
# needed. These helpers parse that message and fold the answers into the
# ``requirements`` dict the blueprint generators already understand.

_PLAN_CARD_PREFIX = "__plan_card__:"


def _parse_plan_card_message(message: str) -> dict:
    """Parse a ``__plan_card__:{json}`` message into an answers dict.

    Returns ``{}`` for any message without the prefix or on JSON failure — so a
    plain-text follow-up falls through to the existing clarification path.
    """
    if not isinstance(message, str) or not message.startswith(_PLAN_CARD_PREFIX):
        return {}
    try:
        parsed = json.loads(message[len(_PLAN_CARD_PREFIX):])
        return parsed if isinstance(parsed, dict) else {}
    except Exception:
        return {}


def _original_user_prompt(session, fallback: str = "") -> str:
    """Return the user's FIRST real prompt from the session history.

    When the Plan Card is answered, ``request.message`` is the internal
    ``__plan_card__:{...}`` protocol string — NOT the user's actual request. The
    real prompt is the first ``role == "user"`` message captured on turn 1.
    Skips any ``__plan_card__:`` control messages so seeding ``requirements`` with
    a clean purpose never leaks the protocol string into the generator prompt.
    """
    for m in (getattr(session, "messages", None) or []):
        if m.get("role") != "user":
            continue
        content = str(m.get("content", "")).strip()
        if content and not content.startswith(_PLAN_CARD_PREFIX):
            return content
    return fallback


def _append_note(requirements: dict, note: str) -> None:
    """Append a line to ``requirements['additional_notes']`` (create if absent)."""
    if not note:
        return
    prev = requirements.get("additional_notes") or ""
    requirements["additional_notes"] = (prev + ("\n" if prev else "") + note).strip()


def _merge_plan_card(requirements: Optional[dict], answers: dict, factory: str) -> dict:
    """Map Plan Card answer IDs onto the structured ``requirements`` fields the
    blueprint generators consume. Unknown IDs are folded into ``additional_notes``
    so nothing is silently lost. Idempotent and null-safe.
    """
    req = dict(requirements or {})
    if not answers:
        return req

    def _val(key):
        v = answers.get(key)
        return v.strip() if isinstance(v, str) else v

    if factory == "agent":
        if _val("audience"):
            _append_note(req, f"Audience: {_val('audience')}")
        if _val("tone"):
            req["tone"] = _val("tone")
        if _val("escalation"):
            req["escalation_policy"] = _val("escalation")
        rs = _val("refusal_scope")
        if rs and rs != "None specified":
            _append_note(req, f"Must not: {rs}")
        # Developer-agent decisions → hard constraints in additional_notes + outputs.
        if _val("repos"):
            _append_note(req, f"Repos: {_val('repos')}")
        if _val("branches"):
            _append_note(req, f"Branches: {_val('branches')}")
        if _val("languages"):
            _append_note(req, f"Languages: {_val('languages')}")
        ct = _val("code_tasks")
        if ct:
            _append_note(req, f"Code tasks: {ct}")
            if ct == "Review only":
                req["outputs"] = "Code review comments"
            elif ct in ("Generate code", "All of the above"):
                req["outputs"] = "Code changes"
            elif ct == "Write tests":
                req["outputs"] = "Test files"
        aa = _val("autonomous_approve")
        if aa:
            if aa.startswith("No"):
                _append_note(req, "Must not approve/merge changes autonomously — a human must approve.")
            else:
                _append_note(req, f"May approve/merge autonomously: {aa}")
        dl = _val("detail_level")
        if dl and dl != "Standard":
            _append_note(req, f"Instruction detail: {dl}")

    elif factory == "workflow":
        tt = _val("trigger_type")
        if tt:
            # Map the Plan Card chip label to the canonical downstream trigger
            # enum ('manual' | 'scheduled' | 'event_driven' | 'api_call'; see
            # agent_factory/pipeline.py). A naive lower/split produced "event"
            # and "api call", neither of which matches — so the value silently
            # fell back to manual. Map explicitly instead.
            _TRIGGER_MAP = {
                "manual": "manual",
                "scheduled": "scheduled",
                "event/webhook": "event_driven",
                "api call": "api_call",
            }
            req["trigger_type"] = _TRIGGER_MAP.get(tt.strip().lower(), "manual")
        fp = _val("failure_policy")
        if fp:
            if fp == "Ask a human":
                req["needs_human_review"] = True
            _append_note(req, f"Failure policy: {fp}")
        ag = _val("approval_gate")
        if ag and ag != "No approval needed":
            req["needs_human_review"] = True
            _append_note(req, f"Approval: {ag}")
        sc = _val("step_count")
        if sc and sc != "Let AI decide":
            _append_note(req, f"Expected steps: {sc}")
        share = _val("share_context")
        if share and share.startswith("No"):
            _append_note(req, "Agents run independently — do not pass results forward.")
        # Q6 external systems — multi-select list → required_services (hard constraint).
        ext = answers.get("external_systems")
        if isinstance(ext, str):
            ext = [ext]
        if isinstance(ext, list):
            services = [s for s in ext if isinstance(s, str) and s and s != "None — reasoning only"]
            if services:
                req["required_services"] = services
                _append_note(req, f"Must connect to: {', '.join(services)}")

    elif factory == "skill":
        if _val("output_format"):
            req["output_format"] = _val("output_format")
        aw = _val("avoid_when")
        if aw and aw != "None specified":
            _append_note(req, f"Do not use when: {aw}")
        dl = _val("detail_level")
        if dl and dl != "Standard":
            _append_note(req, f"Instruction detail: {dl}")
        if _val("include_examples"):
            req["include_examples"] = _val("include_examples")

    return req


def _validate_required_services(required_services: list, catalog_tools: list) -> list:
    """Return declared services that have ZERO tools in the catalog (no LLM).

    An empty return means every declared service is satisfiable.
    """
    available = {
        (t.get("service") or "").strip().lower()
        for t in (catalog_tools or [])
    }
    available.discard("")
    return [
        svc for svc in (required_services or [])
        if isinstance(svc, str) and svc.strip().lower() not in available
    ]


async def _resolve_agent_model(agent_id: str, owner_user_id: str = "") -> str:
    """Resolve an agent's configured model the SAME way AgentRunner does.

    This MUST mirror ``AgentRunner._load_agent`` (agent_factory/pipeline.py)
    because the runtime loads the agent from Postgres — NOT the JSON registry.
    A previous version read only ``_registry`` (the file store), which is empty
    on postgres-backed deployments, so the model always fell back to the cloud
    ``factory_model()`` and local-model agents were still blocked by budget.

    Resolution order (matches ``_load_agent``):
      1. Postgres ``agents`` table (owner-scoped, then id-only fallback).
      2. Legacy AgentRegistry JSON store.
      3. ``factory_model()`` default when nothing pins a model.

    Postgres rows expose the model as ``model_name`` (see ``_row_to_agent``);
    the JSON store uses ``model`` / ``model_name``.
    """
    agent: dict = {}
    try:
        from app import workflow_repo
        row = None
        if owner_user_id:
            row = await workflow_repo.get_agent(agent_id, owner_user_id)
        if not row:
            row = await workflow_repo.get_agent_by_id(agent_id)
        if row:
            agent = row
    except Exception as exc:  # noqa: BLE001
        logger.warning(f"[AGENT] _resolve_agent_model: postgres lookup failed for {agent_id}: {exc}")

    if not agent:
        try:
            agent = _registry.load(agent_id) or {}
        except Exception as exc:  # noqa: BLE001
            logger.warning(f"[AGENT] _resolve_agent_model: registry lookup failed for {agent_id}: {exc}")
            agent = {}

    return agent.get("model") or agent.get("model_name") or factory_model()


async def _agent_uses_local_model(agent_id: str, owner_user_id: str = "") -> bool:
    """True when the agent's configured model is a cost-exempt local model.

    Local models incur no spend, so they must never be blocked by the budget
    preflight. Fails safe (treat as NOT local → enforce budget) on any lookup
    error so cloud models stay enforced.
    """
    try:
        model = await _resolve_agent_model(agent_id, owner_user_id)
        is_local = _is_local_model(model)
        logger.info(
            f"[AGENT] budget-preflight: agent={agent_id} resolved_model={model!r} "
            f"is_local={is_local} (budget {'SKIPPED' if is_local else 'ENFORCED'})"
        )
        return is_local
    except Exception as exc:  # noqa: BLE001
        logger.warning(f"[AGENT] _agent_uses_local_model: failed for {agent_id} → enforce budget: {exc}")
        return False


async def _agent_config_downgraded_to(
    agent_id: str,
    owner_user_id: str,
    fallback_model: str,
    base_config: Optional[dict] = None,
) -> Optional[dict]:
    """Load the agent config and re-point it at ``fallback_model``.

    Used when the budget store is down: instead of refusing the run we execute
    the same agent on a no-cost local model so the user still gets an answer
    while cloud spend stays blocked (see ``governance.check_budget_allowed``).

    ``base_config`` lets a caller that already resolved a config (e.g. the
    template-preview path) downgrade that instead of re-loading.

    Returns None when the config cannot be resolved — the caller then denies
    the run rather than silently continuing on the paid model.
    """
    if not fallback_model:
        return None
    try:
        agent: dict = dict(base_config) if base_config else {}
        if not agent:
            from app import workflow_repo as _repo
            row = None
            if owner_user_id:
                row = await _repo.get_agent(agent_id, owner_user_id)
            if not row:
                row = await _repo.get_agent(agent_id)
            if row:
                agent = dict(row)
            else:
                agent = dict(_registry.load(agent_id) or {})
        if not agent:
            logger.warning(
                f"[AGENT] budget-degraded downgrade: could not resolve config for "
                f"agent={agent_id} → deny"
            )
            return None
        # Both keys are written so whichever one the runtime reads wins.
        agent["model"] = fallback_model
        agent["model_name"] = fallback_model
        logger.info(
            f"[AGENT] budget-degraded downgrade: agent={agent_id} re-pointed at "
            f"local model {fallback_model!r}"
        )
        return agent
    except Exception as exc:  # noqa: BLE001
        logger.warning(f"[AGENT] budget-degraded downgrade failed for {agent_id} → deny: {exc}")
        return None


# ---------------------------------------------------------------------------
# "Already exists" semantic matching — shared across the three factories
# ---------------------------------------------------------------------------
#
# After a factory has gathered enough requirements to generate, we first check
# whether an existing workflow / agent / skill already covers the request. When
# a confident match is found the factory recommends opening/reusing it instead
# of building a near-duplicate (see semantic_match_existing in factory_utils).

# Phrases the user can send from the "Build new anyway" affordance (or type) to
# dismiss the recommendation and force generation. Matched case-insensitively
# as an exact-ish intent so a normal build request isn't accidentally caught.
_BUILD_ANYWAY_SENTINEL = "__build_new_anyway__"


def _wants_build_anyway(message: str) -> bool:
    """True when the user chose to ignore existing matches and build new."""
    m = (message or "").strip().lower()
    if m == _BUILD_ANYWAY_SENTINEL:
        return True
    return m in {
        "build new anyway", "build anyway", "create new anyway",
        "build it anyway", "no, build new", "create new",
    }


