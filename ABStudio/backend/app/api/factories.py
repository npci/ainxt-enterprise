@router.post("/agent-runner/chat")
async def agent_runner_chat(
    request: _AgentRunnerChatReq,
    http_request: Request,
    current_user: AuthenticatedUser = Depends(require_access),
):
    """
    Run a factory-created agent (looked up from AgentRegistry) with the
    given message and optional history. Uses MonitoringLogger.

    Persists the conversation in agent_chat_threads, scoped per user. When
    thread_id is supplied, the saved history is the source of truth and the
    client-provided history list is ignored. When omitted, a new thread is
    started and its id is returned so the client can continue it.
    """
    await _enforce_agent_governance(request.agent_id, current_user)
    store = _agent_chat.get_store()

    thread_id = request.thread_id or _uuid.uuid4().hex

    # ── Budget preflight ────────────────────────────────────────────────
    # Local models incur no spend, so never block them on budget — only
    # enforce for cloud/paid models (see _agent_uses_local_model). Shared
    # policy — see deps.enforce_budget_or_downgrade.
    _budget = await enforce_budget_or_downgrade(
        user_id=current_user.id,
        endpoint="abstudio.agent.chat",
        skip_check=await _agent_uses_local_model(request.agent_id, current_user.id),
        downgrade=lambda m: _agent_config_downgraded_to(
            request.agent_id, current_user.id, m,
        ),
        audit_kwargs=dict(
            thread_id=thread_id,
            email=current_user.email,
            department=getattr(current_user, "department", "") or "",
        ),
    )
    budget_downgrade_config = _budget.config

    # Stamp agent.log lines for this request (request_id / chat_id=thread_id /
    # user_id / span / client_source). Cleared in the finally below.
    bind_log_context(current_user, thread_id=thread_id, request=http_request, span="agent_chat")
    if request.thread_id:
        saved = await store.load_messages(request.thread_id, current_user.id)
        # Carry generated_files on prior turns so re-saving the thread (this
        # turn's save rewrites the whole message list) doesn't strip download
        # chips off earlier assistant turns.
        prior = (
            [
                {
                    "role": m.role,
                    "content": m.content,
                    **({"generated_files": m.generated_files} if getattr(m, "generated_files", None) else {}),
                }
                for m in saved
            ]
            if saved is not None else []
        )
    else:
        prior = list(request.history or [])

    runner = AgentRunner(_registry, _monitor)
    try:
        result = await runner.run(
            request.agent_id, request.message, prior,
            user_id=current_user.id, email=current_user.email,
            department=current_user.department or "",
            is_admin=(current_user.role or "").lower() == "admin",
            agent_config=budget_downgrade_config,
        )
        response = result["response"]
        gen_files = result.get("generated_files") or []
        usage = result.get("usage")
        full = prior + [
            {"role": "user",      "content": request.message},
            # Persist the assistant turn's generated files + usage so download
            # chips and the usage footer re-render on thread reload.
            {"role": "assistant", "content": response, "generated_files": gen_files, "usage": usage},
        ]
        try:
            await store.save_messages(
                thread_id, request.agent_id, current_user.id,
                [
                    _ChatMessage(
                        role=m["role"],
                        content=m["content"],
                        generated_files=m.get("generated_files") or None,
                        usage=m.get("usage") or None,
                    )
                    for m in full
                ],
            )
        except Exception:
            logger.exception(f'[AGENT] agent_runner_chat: failed to persist thread {thread_id}')

        return {
            "agent_id":         request.agent_id,
            "thread_id":        thread_id,
            "response":         response,
            "generated_files":  result["generated_files"],
            # Events emitted by sub-agent delegations during this turn.
            # The frontend renders them as collapsible pills inline with
            # the assistant's response. Empty list for non-delegating
            # agents — older clients can ignore the field safely.
            "delegation_events": result.get("delegation_events", []),
            "usage":            usage,
            # Present only when the budget store was down and this turn ran on
            # a no-cost local model instead of the configured cloud model.
            **({"budget_notice": _budget.notice} if _budget.notice else {}),
        }
    except ValueError as exc:
        raise HTTPException(status_code=404, detail=str(exc))
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))
    finally:
        clear_log_context()


# Sentinel used by the chat-stream endpoint's queue drainer to know
# AgentRunner.run has finished.
_AGENT_RUN_DONE = object()


@router.post("/agent-runner/chat-stream")
async def agent_runner_chat_stream(
    request: _AgentRunnerChatReq,
    http_request: Request,
    current_user: AuthenticatedUser = Depends(require_access),
):
    """SSE counterpart to ``/agent-runner/chat``.

    Streams the swarm's ``subagent_start`` / ``subagent_complete`` events
    in real time so the agent-tab Chat Panel can render the live
    "N sub-agents working" counter and per-sub-agent pills, then emits
    a final ``agent_chat_complete`` event with the assistant response,
    generated files, and the full decoded ``delegation_events`` list.

    The persistence + history-loading semantics are identical to
    ``/agent-runner/chat`` so a thread can be resumed across either
    endpoint without divergence.
    """
    await _enforce_agent_governance(request.agent_id, current_user)
    store = _agent_chat.get_store()

    thread_id = request.thread_id or _uuid.uuid4().hex

    # ── Template-preview resolution ────────────────────────────────────
    # When ``template_id`` is set the caller wants to chat with an agent
    # TEMPLATE directly, without cloning it into a saved agent row. We
    # load the template (department-scoped) and hand the resolved config
    # to AgentRunner so it skips the agents-table lookup. No row is
    # created, so the preview never appears in "My Agents" and the
    # governance "Deploy" affordance never lights up. Mirrors the
    # workflow template "Try it" flow.
    resolved_agent_config = None
    effective_agent_id = request.agent_id
    if request.template_id:
        template = await workflow_repo.get_agent_template(
            request.template_id,
            department=getattr(current_user, "department", "") or "",
            is_admin=(current_user.role or "").lower() == "admin",
        )
        if not template:
            raise HTTPException(status_code=404, detail="Agent template not found")
        effective_agent_id = f"template::{request.template_id}"
        # Shape the template row into the agent dict AgentRunner expects.
        # Templates don't carry guardrails/memory_config/attached_flows, so
        # fall back to the same defaults create_agent uses.
        resolved_agent_config = {
            "id":             effective_agent_id,
            "name":           template.get("name", "Template"),
            "description":    template.get("description", ""),
            "instructions":   template.get("instructions", ""),
            "provider":       template.get("provider", "custom"),
            "model_name":     template.get("model_name", ""),
            "temperature":    template.get("temperature", 0.7),
            "max_tokens":     template.get("max_tokens", 2048),
            "top_p":          template.get("top_p", 1.0),
            "tools":          template.get("tools") or [],
            "skills":         template.get("skills") or [],
            "guardrails":     {},
            "memory_config":  {},
            "attached_flows": [],
            "use_subagents":  False,
        }

    # ── Budget preflight ────────────────────────────────────────────────
    # Local models incur no spend, so never block them on budget — only
    # enforce for cloud/paid models (see _agent_uses_local_model). Shared
    # policy — see deps.enforce_budget_or_downgrade. Downgrades the
    # already-resolved template config when this is a template preview.
    _budget = await enforce_budget_or_downgrade(
        user_id=current_user.id,
        endpoint="abstudio.agent.chat_stream",
        skip_check=await _agent_uses_local_model(effective_agent_id, current_user.id),
        downgrade=lambda m: _agent_config_downgraded_to(
            effective_agent_id, current_user.id, m,
            base_config=resolved_agent_config,
        ),
        audit_kwargs=dict(
            thread_id=thread_id,
            email=current_user.email,
            department=getattr(current_user, "department", "") or "",
        ),
    )
    if _budget.config is not None:
        resolved_agent_config = _budget.config

    if request.thread_id:
        saved = await store.load_messages(request.thread_id, current_user.id)
        # Carry generated_files on prior turns so re-saving the thread (this
        # turn's save rewrites the whole message list) doesn't strip download
        # chips off earlier assistant turns.
        prior = (
            [
                {
                    "role": m.role,
                    "content": m.content,
                    **({"generated_files": m.generated_files} if getattr(m, "generated_files", None) else {}),
                }
                for m in saved
            ]
            if saved is not None else []
        )
    else:
        prior = list(request.history or [])

    runner = AgentRunner(_registry, _monitor)

    # Stamp agent.log lines for this streaming request. asyncio runs the handler
    # and the SSE generator on the same event-loop thread, so this thread-local
    # context is visible throughout the stream; it is reset in event_gen()'s
    # finally.
    bind_log_context(current_user, thread_id=thread_id, request=http_request, span="agent_chat")

    async def event_gen():
        # Re-assert the logging context on the generator's own execution and
        # always reset it when the stream ends.
        bind_log_context(current_user, thread_id=thread_id, request=http_request, span="agent_chat")
        try:
            async for _frame in _event_gen_inner():
                yield _frame
        finally:
            clear_log_context()

    async def _event_gen_inner():
        queue: asyncio.Queue = asyncio.Queue()

        def _emit(frame: str) -> None:
            # SwarmRuntime emits `data: {json}\n\n` frames. We forward
            # them verbatim — same wire format the rest of the SSE
            # endpoints use, so the frontend's existing reader handles
            # them with no changes.
            try:
                queue.put_nowait(frame)
            except Exception:  # noqa: BLE001
                logger.debug('[AGENT] agent_runner_chat_stream: queue.put failed', exc_info=True)

        # Open the stream with a thread-id frame so the client can
        # persist it before the first sub-agent event arrives.
        yield _sse({"event": "start", "data": {"thread_id": thread_id}})

        # Budget store was down and we downgraded to a no-cost local model —
        # tell the user before the answer streams. Reuses `agent_fallback`,
        # which the ChatPanel already renders as a transient notice.
        if _budget.notice:
            yield _sse({"event": "agent_fallback", "data": {
                "agent": "Budget guard",
                "node_id": None,
                "primary_model": "the selected cloud model",
                "fallback_model": _budget.fallback_model,
                "reason": _budget.notice,
            }})

        run_task = asyncio.create_task(runner.run(
            effective_agent_id, request.message, prior,
            user_id=current_user.id, email=current_user.email,
            department=current_user.department or "",
            is_admin=(current_user.role or "").lower() == "admin",
            sse_sink=_emit,
            endpoint="abstudio.agent.chat_stream",
            agent_config=resolved_agent_config,
        ))
        # Sentinel-on-done means we never have to poll with a timeout.
        run_task.add_done_callback(lambda _t: queue.put_nowait(_AGENT_RUN_DONE))

        try:
            while True:
                item = await queue.get()
                if item is _AGENT_RUN_DONE:
                    # Drain any frames buffered between the last get() and
                    # the sentinel landing in the queue.
                    while not queue.empty():
                        leftover = queue.get_nowait()
                        if leftover is _AGENT_RUN_DONE:
                            continue
                        yield leftover
                    break
                if await http_request.is_disconnected():
                    logger.info(f'[AGENT] Client disconnected from /agent-runner/chat-stream; cancelling agent={request.agent_id} thread={thread_id}')
                    break
                # `_emit` always pushes pre-formatted SSE frames; pass through.
                yield item
        finally:
            if not run_task.done():
                run_task.cancel()
                try:
                    await run_task
                except (asyncio.CancelledError, Exception):  # noqa: BLE001
                    pass

        if run_task.cancelled():
            return

        # Surface AgentRunner errors as an SSE error frame, then return.
        try:
            result = run_task.result()
        except ValueError as exc:
            yield _sse({"event": "error", "data": {"detail": str(exc), "code": "not_found"}})
            return
        except Exception as exc:  # noqa: BLE001
            logger.exception('[AGENT] agent_runner_chat_stream: runner raised')
            yield _sse({"event": "error", "data": {"detail": str(exc), "code": "runner_failure"}})
            return

        response = result["response"]
        gen_files = result.get("generated_files") or []
        usage = result.get("usage")
        full = prior + [
            {"role": "user",      "content": request.message},
            # Persist the assistant turn's generated files + usage so download
            # chips and the usage footer re-render on thread reload.
            {"role": "assistant", "content": response, "generated_files": gen_files, "usage": usage},
        ]
        try:
            await store.save_messages(
                thread_id, effective_agent_id, current_user.id,
                [
                    _ChatMessage(
                        role=m["role"],
                        content=m["content"],
                        generated_files=m.get("generated_files") or None,
                        usage=m.get("usage") or None,
                    )
                    for m in full
                ],
            )
        except Exception:
            logger.exception(f'[AGENT] agent_runner_chat_stream: failed to persist thread {thread_id}')

        yield _sse({
            "event": "agent_chat_complete",
            "data": {
                "agent_id":          effective_agent_id,
                "thread_id":         thread_id,
                "response":          response,
                "generated_files":   result.get("generated_files") or [],
                "delegation_events": result.get("delegation_events") or [],
                "usage":             result.get("usage"),
                # Coverage trace from KB full_file retrieval — populated when
                # the agent used a single-doc KB (full_file mode). The frontend
                # reads this to render the same coverage badge as kb chat.
                # None when no full_file KBs were used this turn.
                "coverage_trace":    result.get("coverage_trace"),
            },
        })

    return StreamingResponse(
        event_gen(),
        media_type="text/event-stream",
        headers={
            "Cache-Control":     "no-cache",
            "Connection":        "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )


