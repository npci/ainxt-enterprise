# Friendly display names for known services (fallback = title-cased service id).
_SERVICE_DISPLAY: dict[str, str] = {
    "gitlab": "GitLab",
    "jira": "Jira",
    "slack": "Slack",
    "confluence": "Confluence",
    "github": "GitHub",
    "http": "HTTP request",
    "database": "Database",
    "postgres": "Database",
}

# Emoji chips for the guided question — purely cosmetic, safe fallback.
_SERVICE_ICON: dict[str, str] = {
    "jira": "📋", "gitlab": "🦊", "github": "🐙", "slack": "💬",
    "confluence": "📘", "http": "🌐", "database": "🗄️",
}


def _service_display(service: str) -> str:
    svc = (service or "").strip().lower()
    return _SERVICE_DISPLAY.get(svc, svc.replace("-", " ").replace("_", " ").title() or "a system")


def _friendly_tool_phrase(tool_name: str, catalog_tools: list[dict]) -> str:
    """Turn a raw tool slug into a short human phrase using its catalog
    description, e.g. ``jira-get-issue`` → "read Jira tickets"."""
    tool = next((t for t in (catalog_tools or []) if t.get("name") == tool_name), None)
    if not tool:
        return tool_name
    desc = " ".join(str(tool.get("description") or "").split())
    svc = _service_display(tool.get("service") or "")
    if desc:
        short = desc[:60].rstrip(". ")
        return f"{short} ({svc})" if svc and svc.lower() not in short.lower() else short
    return f"{svc} action" if svc else tool_name


def _available_services_phrase(catalog_tools: list[dict]) -> str:
    """Comma-separated friendly list of every service that exists in the catalog."""
    services = sorted({
        (t.get("service") or "").strip().lower()
        for t in (catalog_tools or []) if (t.get("service") or "").strip()
    })
    if not services:
        return "no integrations yet"
    return ", ".join(f"**{_service_display(s)}**" for s in services)


