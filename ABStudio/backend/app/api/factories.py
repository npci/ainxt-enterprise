@router.post("/agent-factory/chat")
async def agent_factory_chat(
    request: _AgentFactoryChatReq,
    current_user: AuthenticatedUser = Depends(require_access),
):
    """
    Multi-turn SSE endpoint that guides the user through the agent-creation
    pipeline:
      clarification → blueprint → tool matching → audit → assembly → confirm
    """
    # Restore an evicted/persisted session from Postgres if it isn't in the
    # in-memory cache, so a build survives a backend restart. Scoped to the
    # authenticated user.
    session = await get_or_restore_session(request.session_id, current_user.id)
    session.messages.append({"role": "user", "content": request.message})
    session.turn_count += 1

    async def stream():
        try:
            # ---- Greeting short-circuit (turn 1 only) ---------------------
            # A bare "hi"/"hello" shouldn't trigger intent parsing or a Plan
            # Card. Reply with a friendly nudge and reset turn_count so the
            # user's NEXT (real) message is treated as a fresh turn 1.
            if session.stage == "clarifying" and session.turn_count == 1 and _is_greeting(request.message):
                session.turn_count = 0
                ai_msg = _greeting_reply(request.message)
                session.messages.append({"role": "assistant", "content": ai_msg})
                yield _sse({"type": "message", "text": ai_msg, "stage": "clarifying"})
                return

            # ---- Stage: clarifying ----------------------------------------
            if session.stage == "clarifying":
                # ---- Turn 1: parse intent, check existing matches, emit Plan Card ----
                if session.turn_count == 1:
                    yield _sse({"type": "thinking", "text": "Analysing your request…"})
                    # Fire match BEFORE intent parse so both run in parallel.
                    _early_match_task = asyncio.create_task(
                        _find_existing_matches("agent", request.message, current_user.id)
                    )
                    intent = await IntentParser().parse(request.message)
                    session.intent = intent

                    yield _sse({"type": "thinking", "text": "Checking for existing agents that already do this…"})
                    try:
                        early_matches = await _early_match_task
                    except Exception:
                        early_matches = []
                    if early_matches:
                        session.pending_matches = early_matches
                        session.stage = "suggest_existing"
                        ai_msg = _existing_match_message("agent", early_matches)
                        session.messages.append({"role": "assistant", "content": ai_msg})
                        yield _sse({
                            "type": "message",
                            "text": ai_msg,
                            "stage": "suggest_existing",
                            "data": {"existing_matches": early_matches},
                        })
                        return

                    # No strong match — present the structured Plan Card instead of
                    # a conversational clarification question. The user either
                    # accepts defaults ("Generate with these settings") or clicks
                    # "Change something" to fall through to the chat path below.
                    yield _sse({"type": "thinking", "text": "Preparing a few quick questions…"})
                    plan_card = await AgentPlanCardGenerator().generate(session.intent, request.message)
                    session.stage = "plan_card"
                    ai_msg = "Before I build this, let me confirm a few things:"
                    session.messages.append({"role": "assistant", "content": ai_msg})
                    yield _sse({
                        "type": "message",
                        "text": ai_msg,
                        "stage": "plan_card",
                        "data": {"plan_card": plan_card},
                    })
                    return

                # ---- Turn >1: conversational clarification (follow-ups / "Change something") ----
                yield _sse({"type": "thinking", "text": "Reviewing your answers…"})
                yield _sse({"type": "thinking", "text": "Determining what information is still needed…"})
                clar = await ClarificationEngine().get_next_question_or_requirements(
                    session.intent, session.messages
                )
                if not clar.get("done"):
                    question = clar.get("question", "Could you tell me a bit more about what you need?")
                    session.messages.append({"role": "assistant", "content": question})
                    yield _sse({"type": "message", "text": question, "stage": "clarifying", "suggestions": clar.get("suggestions", [])})
                else:
                    session.requirements = clar.get("requirements", {})
                    session.stage = "generating"
                    async for _frame in _build_and_stream_agent(session):
                        yield _frame

            # ---- Stage: Plan Card answered (or "Change something") ----
            elif session.stage == "plan_card":
                answers = _parse_plan_card_message(request.message)
                if answers:
                    # Seed requirements from intent so the blueprint has purpose/inputs
                    # even though the conversational ClarificationEngine was skipped.
                    base_req = session.requirements or {
                        "purpose": (session.intent or {}).get("raw_intent") or _original_user_prompt(session, "a helpful assistant"),
                        "inputs": "user messages or requests",
                        "outputs": "a helpful response in clear text",
                        "integrations": "none",
                        "trigger_type": "manual",
                        "persona": (session.intent or {}).get("inferred_persona") or "friendly and helpful",
                    }
                    session.requirements = _merge_plan_card(base_req, answers, "agent")
                    session.stage = "generating"
                    async for _frame in _build_and_stream_agent(session):
                        yield _frame
                else:
                    # "Change something" / free-text — fall through to conversational
                    # clarification without re-firing the turn-1 plan-card branch.
                    session.stage = "clarifying"
                    yield _sse({"type": "thinking", "text": "Sure — let's talk it through…"})
                    clar = await ClarificationEngine().get_next_question_or_requirements(
                        session.intent, session.messages
                    )
                    if not clar.get("done"):
                        question = clar.get("question", "What would you like to change?")
                        session.messages.append({"role": "assistant", "content": question})
                        yield _sse({"type": "message", "text": question, "stage": "clarifying", "suggestions": clar.get("suggestions", [])})
                    else:
                        session.requirements = clar.get("requirements", {})
                        session.stage = "generating"
                        async for _frame in _build_and_stream_agent(session):
                            yield _frame

            # ---- Stage: user proceeded past existing-match recommendations ---
            elif session.stage == "suggest_existing":
                session.pending_matches = []
                session.messages = _strip_match_messages(session.messages)
                # The match can fire on turn 1 (before requirements were ever
                # gathered), so ``session.requirements`` may still be None here.
                # Instead of dropping into the conversational clarifier (which
                # bypassed the Plan Card entirely), present the Plan Card — the
                # same structured experience the no-match path shows on turn 1.
                if not session.requirements:
                    yield _sse({"type": "thinking", "text": "Preparing a few quick questions…"})
                    plan_card = await AgentPlanCardGenerator().generate(
                        session.intent or {}, _original_user_prompt(session, request.message),
                    )
                    session.stage = "plan_card"
                    ai_msg = "Before I build this, let me confirm a few things:"
                    session.messages.append({"role": "assistant", "content": ai_msg})
                    yield _sse({
                        "type": "message",
                        "text": ai_msg,
                        "stage": "plan_card",
                        "data": {"plan_card": plan_card},
                    })
                    return
                elif not _wants_build_anyway(request.message):
                    prev = session.requirements.get("additional_notes", "")
                    session.requirements["additional_notes"] = (
                        prev + f"\nUser added: {request.message}"
                    ).strip()
                session.stage = "generating"
                async for _frame in _build_and_stream_agent(session):
                    yield _frame

            # ---- Stage: confirm — user wants a targeted change -----------
            elif session.stage == "confirm":
                # Fold any live edits the frontend has made in the config
                # panel back into the session's assembled dict FIRST so the
                # patcher (and any later deploy) sees the user's current view
                # of the config — not the last blueprint the backend built.
                # Tools / skills are catalog-resolved lists (not chat-patchable
                # fields) but must still be mirrored here so a manual add/remove
                # survives the next SSE round trip.
                _SYNC_ONLY_FIELDS = ("tools", "skills")
                if isinstance(request.current_assembled_override, dict) and session.assembled:
                    _live = request.current_assembled_override
                    for _k in AgentFieldPatcher.ALLOWED_FIELDS + _SYNC_ONLY_FIELDS:
                        if _k in _live and _live[_k] is not None:
                            session.assembled[_k] = _live[_k]

                if not session.assembled:
                    msg = "I lost track of the agent config. Let's start over — what should it do?"
                    session.stage = "clarifying"
                    session.messages.append({"role": "assistant", "content": msg})
                    yield _sse({"type": "message", "text": msg, "stage": "clarifying"})
                    return

                yield _sse({"type": "thinking", "text": "Figuring out what to change…"})
                patch = await AgentFieldPatcher().patch(session.assembled, request.message)

                # Validate a proposed ``model`` change against the same
                # catalogue the ``/llm/models`` dropdown uses so a hallucinated
                # id (e.g. "model", "gpt-99") is rejected before it lands.
                # Fuzzy matching also lets the user say things like "sonnet"
                # and get resolved to a real id ("claude-sonnet-4-6") — that
                # already works in the LLM patcher, but this guard ensures
                # the final value is always one the runtime can serve.
                model_rejected_reason = ""
                _mentions_model = _message_asks_for_model_change(request.message)
                if "model" in patch or _mentions_model:
                    _requested = str(patch.get("model") or "").strip()
                    # Fallback: if the LLM didn't return a model but the user
                    # message mentioned it, try to extract the requested name
                    # from the message itself (e.g. "change model to xyz").
                    if not _requested and _mentions_model:
                        _requested = _extract_model_token(request.message)
                    if _requested:
                        try:
                            _catalogue = await resolve_available_models(current_user)
                            _allowed_ids = list(_catalogue.get("models") or [])
                        except Exception:
                            logger.debug('[AGENT] model catalogue lookup failed', exc_info=True)
                            _allowed_ids = []
                        _resolved = _resolve_model_alias(_requested, _allowed_ids)
                        if _resolved:
                            patch["model"] = _resolved
                        else:
                            model_rejected_reason = _build_model_rejection_message(
                                _requested, _allowed_ids
                            )
                            patch.pop("model", None)

                if not patch:
                    if model_rejected_reason:
                        ai_msg = model_rejected_reason
                    else:
                        # LLM didn't identify any editable field — likely a
                        # clarification or off-topic reply. Give the user a
                        # helpful nudge without touching the config.
                        ai_msg = (
                            "I couldn't tell which setting to change from that. "
                            "You can either tweak the fields on the right directly, "
                            "or tell me something like 'make the system prompt more "
                            "aggressive', 'switch to claude-haiku', or 'set temperature to 0.2'. "
                            "When you're happy, click **Deploy Agent** to save it."
                        )
                    session.messages.append({"role": "assistant", "content": ai_msg})
                    yield _sse({
                        "type": "message",
                        "text": ai_msg,
                        "stage": "confirm",
                        "data": {"assembled": session.assembled},
                    })
                    return

                yield _sse({"type": "thinking", "text": "Applying the change…"})
                session.assembled = AgentFieldPatcher.apply(session.assembled, patch)

                # Build a short human-readable summary of exactly what changed.
                _changed_labels = {
                    "name": "name",
                    "description": "description",
                    "system_prompt": "system prompt",
                    "persona": "persona",
                    "model": "model",
                    "model_params": "model parameters",
                    "knowledge": "knowledge base",
                    "hitl_mode": "human-in-the-loop mode",
                }
                _lines = ["Updated:"]
                for _f in patch.keys():
                    _label = _changed_labels.get(_f, _f)
                    if _f == "model":
                        _lines.append(f"- **{_label}** → `{patch[_f]}`")
                    elif _f == "model_params":
                        _mp = patch[_f]
                        _parts = ", ".join(f"{k}={v}" for k, v in _mp.items())
                        _lines.append(f"- **{_label}** → {_parts}")
                    elif _f == "hitl_mode":
                        _lines.append(f"- **{_label}** → `{patch[_f]}`")
                    elif _f == "knowledge":
                        _lines.append(f"- **{_label}** → mode=`{patch[_f].get('mode')}`")
                    else:
                        _lines.append(f"- **{_label}** updated")
                _lines.append("\nThe right panel now reflects the change. "
                              "Keep chatting to refine more fields, or click **Deploy Agent** when ready.")
                ai_msg = "\n".join(_lines)
                # Prepend the model rejection notice so the user knows their
                # model request was ignored even when other fields DID land.
                if model_rejected_reason:
                    ai_msg = model_rejected_reason + "\n\n" + ai_msg
                session.messages.append({"role": "assistant", "content": ai_msg})
                yield _sse({
                    "type": "message",
                    "text": ai_msg,
                    "stage": "confirm",
                    "data": {"assembled": session.assembled, "patched_fields": list(patch.keys())},
                })

        except Exception as exc:
            logger.exception('[AGENT] agent_factory_chat error')
            try:
                yield _sse({"type": "error", "message": str(exc)})
            except Exception:
                pass
        finally:
            # Write-through the session state so the build can resume after a
            # restart. Scheduled (not awaited) so a Postgres round-trip never
            # delays the client's `done` event. Best-effort; failures are
            # swallowed inside persist_session.
            _schedule_bg(persist_session(session, current_user.id))
            yield _sse({"type": "done", "session_id": session.session_id, "stage": session.stage})

    return StreamingResponse(
        stream(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "Connection": "keep-alive", "X-Accel-Buffering": "no"},
    )


@router.post("/agent-factory/confirm")
async def agent_factory_confirm(
    request: _AgentFactoryConfirmReq,
    current_user: AuthenticatedUser = Depends(require_access),
):
    """
    Save the assembled agent to AgentRegistry and create a corresponding
    workflow entry so the card appears in the Dashboard.
    """
    # Restore from Postgres if the in-memory session was evicted or the
    # backend restarted between the build chat and this confirm.
    session = await get_or_restore_session(request.session_id, current_user.id)
    if not session or not session.assembled:
        raise HTTPException(status_code=400, detail="No assembled agent for this session. Complete the factory chat first.")

    assembled = session.assembled

    agent_id = assembled.get("agent_id") or str(_uuid.uuid4())
    assembled["agent_id"] = agent_id

    # Apply the frontend's inline edits (from the preview overlay) BEFORE
    # persisting so what the user sees is what lands in the DB.
    if request.name_override:
        assembled["name"] = request.name_override
    if request.description_override is not None:
        assembled["description"] = request.description_override
    if request.system_prompt_override is not None:
        assembled["system_prompt"] = request.system_prompt_override

    base_prompt = _coerce_to_text(
        assembled.get("system_prompt"),
        fallback="You are a helpful assistant.",
    )
    persona = _coerce_to_text(assembled.get("persona"), fallback="").strip()
    instructions = base_prompt + (f"\n\nPersona: {persona}" if persona else "")

    _provider = "custom"
    _default_model = factory_model()

    # Runtime config precedence:
    #   1. explicit override from the preview overlay
    #   2. blueprint values coerced by _apply_domain_defaults (assembled.*)
    #   3. safe fallbacks (only reached when the blueprint itself is bogus)
    _mp_from_bp = assembled.get("model_params") or {}
    _mp_override = request.model_params_override or {}
    def _pick_float(key, fallback):
        v = _mp_override.get(key)
        if v is None:
            v = _mp_from_bp.get(key)
        try:
            return float(v) if v is not None else fallback
        except (TypeError, ValueError):
            return fallback
    def _pick_int(key, fallback):
        v = _mp_override.get(key)
        if v is None:
            v = _mp_from_bp.get(key)
        try:
            return int(float(v)) if v is not None else fallback
        except (TypeError, ValueError):
            return fallback

    temperature = _pick_float("temperature", 0.3)
    max_tokens  = _pick_int("max_tokens",   4096)
    top_p       = _pick_float("top_p",       0.9)

    # Model: explicit override wins → assembled/blueprint choice → factory default.
    _model_name = (
        (request.model_name_override or "").strip()
        or (assembled.get("model") or "").strip()
        or _default_model
    )

    # Knowledge: override wins; otherwise use blueprint value.
    _kb_blob = request.knowledge_override or assembled.get("knowledge") or {"mode": "none", "namespaces": []}
    # Normalise so the DB always gets the canonical shape.
    if isinstance(_kb_blob, dict):
        _kb_mode = str(_kb_blob.get("mode") or "none").lower()
        if _kb_mode not in ("none", "existing_kb", "add_kb"):
            _kb_mode = "none"
        _kb_ns = _kb_blob.get("namespaces") or []
        if not isinstance(_kb_ns, list):
            _kb_ns = []
        _kb_blob = {"mode": _kb_mode, "namespaces": list(_kb_ns)}
    else:
        _kb_blob = {"mode": "none", "namespaces": []}

    # HITL: override wins; otherwise use blueprint value. Stored inside
    # guardrails since the ``agents`` table has no dedicated column.
    _hitl_mode = (request.hitl_mode_override or assembled.get("hitl_mode") or "off").strip().lower()
    if _hitl_mode not in ("off", "before_tool", "after_response"):
        _hitl_mode = "off"

    _guardrails = dict(assembled.get("guardrails") or {})
    _guardrails["hitl_mode"] = _hitl_mode

    try:
        # ── Catalog-guard on confirm ──────────────────────────────────────────
        # tools_override / skills_override come from the frontend config panel
        # (the user may have manually added entries) or from the assembled dict
        # produced by the factory pipeline.  Either way, filter against the live
        # catalog so no hallucinated / non-existent tool name ever reaches the DB.
        # code_executor is always allowed (auto-injected by AgentAssembler and
        # never in the user-facing catalog).
        _ALWAYS_ALLOWED_TOOLS = {"code_executor"}
        try:
            _confirm_catalog_skills, _confirm_catalog_tools = await catalog_cache.get()
            _valid_tool_names  = {t["name"] for t in _confirm_catalog_tools} | _ALWAYS_ALLOWED_TOOLS
            _valid_skill_names = {s["name"] for s in _confirm_catalog_skills}
        except Exception:
            # Catalog unavailable — skip the filter rather than blocking the save.
            _valid_tool_names  = None
            _valid_skill_names = None

        def _filter_tools(raw: list) -> list:
            if _valid_tool_names is None:
                return raw
            kept, dropped = [], []
            for t in (raw or []):
                name = t.get("name") if isinstance(t, dict) else str(t or "")
                if name in _valid_tool_names:
                    kept.append(t)
                else:
                    dropped.append(name)
            if dropped:
                logger.warning(f'[AGENT] agent_factory_confirm: dropping non-catalog tools: {dropped}')
            return kept

        def _filter_skills(raw: list) -> list:
            if _valid_skill_names is None:
                return raw
            kept, dropped = [], []
            for s in (raw or []):
                name = s.get("name") if isinstance(s, dict) else str(s or "")
                if name in _valid_skill_names:
                    kept.append(s)
                else:
                    dropped.append(name)
            if dropped:
                logger.warning(f'[AGENT] agent_factory_confirm: dropping non-catalog skills: {dropped}')
            return kept

        tools  = _filter_tools(request.tools_override  if request.tools_override  is not None else assembled.get("tools",  []))
        skills = _filter_skills(request.skills_override if request.skills_override is not None else assembled.get("skills", []))
        await workflow_repo.create_agent({
            "id":            agent_id,
            "name":          assembled.get("name", "New Agent"),
            "description":   assembled.get("description", ""),
            "instructions":  instructions,
            "provider":      _provider,
            "model_name":    _model_name,
            "api_key":       "",
            "temperature":   temperature,
            "max_tokens":    max_tokens,
            "top_p":         top_p,
            "base_url":      "",
            "tools":         tools,
            "skills":        skills,
            "guardrails":    _guardrails,
            "memory_config": assembled.get("memory_config", {}),
            "knowledge":     _kb_blob,
        }, current_user.id)
    except NameValidationError as exc:
        raise HTTPException(status_code=400, detail={"error": "invalid_name", "message": str(exc)})
    except Exception as exc:
        logger.exception('[AGENT] agent_factory_confirm: postgres create_agent failed')
        raise HTTPException(
            status_code=500,
            detail=(
                "Failed to save the agent to the database. "
                "If you just updated the backend, restart it so the schema "
                f"migrations run. Underlying error: {exc}"
            ),
        )

    # Reflect all overrides so the response body matches what was deployed.
    assembled["tools"] = tools
    assembled["skills"] = skills
    assembled["model"] = _model_name
    assembled["model_params"] = {
        "temperature": temperature,
        "max_tokens":  max_tokens,
        "top_p":       top_p,
    }
    assembled["knowledge"] = _kb_blob
    assembled["hitl_mode"] = _hitl_mode
    assembled["guardrails"] = _guardrails

    session.agent_id = agent_id
    session.stage = "done"

    # Build saved — drop the persisted draft session.
    try:
        await workflow_repo.delete_factory_session(
            session.session_id, FACTORY_TYPE, current_user.id
        )
    except Exception:
        logger.debug('[AGENT] agent_factory_confirm: session cleanup skipped', exc_info=True)

    return {
        "agent_id": agent_id,
        "agent": assembled,
    }


