def _match_query_from_requirements(requirements: dict) -> str:
    """Compose a short match query from gathered requirements.

    Works for all three factories — each stores a ``name`` plus a
    purpose/description field under a slightly different key.
    """
    req = requirements or {}
    name = str(req.get("name") or req.get("display_name") or "").strip()
    purpose = str(
        req.get("purpose")
        or req.get("description")
        or req.get("goal")
        or ""
    ).strip()
    return f"{name}. {purpose}".strip(". ").strip()


async def _find_existing_matches(kind: str, query: str, user_id: str) -> list[dict]:
    """Return existing items (annotated with routing ``kind``) matching ``query``.

    ``kind`` is one of ``"workflow"``, ``"agent"``, ``"skill"``. Candidate
    records carry a per-item ``kind`` so the frontend knows how to open them
    (a saved workflow vs. a workflow template, etc.). Fails safe to ``[]``.
    """
    from app.core.factory_utils import semantic_match_existing

    # Product decision: recommend ONLY curated templates — never the user's own
    # saved workflows/agents. Opening a template routes through the same
    # "use template" flow as the Workflows/Agents front page, so the user gets
    # a clean, faithful instantiation (conditional nodes and all) rather than a
    # near-duplicate of something they already built.
    # Use the template candidate cache — avoids a DB round-trip on every
    # match call. Cache is shared across all three factory kinds and refreshes
    # every 5 minutes (FACTORY_TEMPLATE_CACHE_TTL_S). This means the match
    # task goes straight to the LLM rather than waiting on postgres first,
    # making the parallel early-match actually run concurrently with clarification.
    try:
        candidates = await template_candidate_cache.get(kind)
    except Exception:
        logger.warning(f'[AGENT] _find_existing_matches: candidate cache load failed for kind={kind} — semantic match will be skipped this turn', exc_info=True)
        return []
    logger.info(f"[AGENT] _find_existing_matches: kind={kind} query={(query or '')[:120]!r} candidates={len(candidates)}")
    if not candidates:
        return []
    result = await semantic_match_existing(query, candidates)
    logger.info(f'[AGENT] _find_existing_matches: kind={kind} matched={len(result)}')
    return result


async def _build_and_stream_agent(session):
    """Run the agent blueprint → match → assemble pipeline for ``session``.

    Async generator yielding SSE frames (progress ``thinking`` events plus the
    final ``message`` event). Mutates ``session`` in place: sets
    ``session.blueprint``, ``session.assembled`` and advances ``session.stage``
    to ``"confirm"``. Extracted from the inline ``/agent-factory/chat`` handler
    so both the first-generation path and the post-``suggest_existing`` path
    share one implementation.
    """
    from app.core.factory_utils import keyword_match_tools, keyword_match_skills

    yield _sse({"type": "thinking", "text": "Loading catalog…"})
    _catalog_skills, _catalog_tools = await catalog_cache.get()

    _AF_AUTO_INJECTED = {"code_executor"}
    _assignable_tools = [t for t in _catalog_tools if t["name"] not in _AF_AUTO_INJECTED]
    _tg: dict[str, int] = {}
    for _t in _assignable_tools:
        _sv = (_t.get("service") or "other").strip() or "other"
        _tg[_sv] = _tg.get(_sv, 0) + 1
    _tp = ", ".join(f"{c} {s}" for s, c in sorted(_tg.items(), key=lambda x: -x[1]))
    yield _sse({"type": "thinking", "text": f"Found {len(_assignable_tools)} tools ({_tp}) and {len(_catalog_skills)} skills"})

    yield _sse({"type": "thinking", "text": "Designing agent blueprint…"})
    blueprint = await AgentBlueprintGenerator().generate(
        session.requirements,
        available_skills=_catalog_skills,
        available_tools=_assignable_tools,
    )
    session.blueprint = blueprint

    yield _sse({"type": "thinking", "text": "Matching tools and skills from catalog…"})
    matcher = ToolSkillMatcher()
    audit = await CapabilityAudit(matcher).audit(blueprint)

    if audit["tool_gaps"]:
        logger.info(f"[AGENT] agent_factory: dropping unmatched tools: {audit['tool_gaps']}")
    if audit["skill_gaps"]:
        logger.info(f"[AGENT] agent_factory: dropping unmatched skills: {audit['skill_gaps']}")

    resolved_tools = audit["resolved_tools"]
    resolved_skills = audit["resolved_skills"]

    _tools_by_name = {t["name"]: t for t in _assignable_tools}
    _skills_by_name = {s["name"]: s for s in _catalog_skills}

    if not resolved_tools:
        agent_name = blueprint.get("name", "")
        agent_desc = blueprint.get("description", "") + " " + blueprint.get("system_prompt", "")
        fallback_tool_names = keyword_match_tools(agent_name, agent_desc, _assignable_tools, search_instructions=True)
        if fallback_tool_names:
            logger.info(f'[AGENT] agent_factory: keyword fallback matched tools: {fallback_tool_names}')
            for tname in fallback_tool_names:
                item = _tools_by_name.get(tname)
                if item:
                    resolved_tools.append({
                        "name": item["name"],
                        "description": item.get("description", ""),
                        "input_schema": item.get("input_schema") or {},
                        "score": 0.7,
                        "requested_name": tname,
                    })
    if not resolved_skills:
        agent_name = blueprint.get("name", "")
        agent_desc = blueprint.get("description", "") + " " + blueprint.get("system_prompt", "")
        fallback_skill_names = keyword_match_skills(agent_name, agent_desc, _catalog_skills, search_instructions=True)
        if fallback_skill_names:
            logger.info(f'[AGENT] agent_factory: keyword fallback matched skills: {fallback_skill_names}')
            for sname in fallback_skill_names:
                item = _skills_by_name.get(sname)
                if item:
                    resolved_skills.append({
                        "name": item["name"],
                        "description": item.get("description", ""),
                        "category": item.get("category"),
                        "score": 0.7,
                        "requested_name": sname,
                    })

    yield _sse({"type": "thinking", "text": "Assembling final agent configuration…"})
    assembled = AgentAssembler().assemble(blueprint, resolved_tools, resolved_skills)
    session.assembled = assembled
    session.stage = "confirm"

    tool_names = [t.get("name", "") for t in assembled["tools"]]
    skill_names = [s.get("name", "") for s in assembled["skills"]]

    _matched_parts = []
    _real_tools = [n for n in tool_names if n != "code_executor"]
    if _real_tools:
        _matched_parts.append(f"tools: {', '.join(_real_tools)}")
    if skill_names:
        _matched_parts.append(f"skills: {', '.join(skill_names)}")
    if _matched_parts:
        yield _sse({"type": "thinking", "text": f"Attached {' | '.join(_matched_parts)}"})

    lines = [
        "Your agent is ready!\n",
        f"### {assembled['name']}",
        f"{assembled['description']}\n" if assembled.get('description') else "",
    ]
    if _real_tools:
        lines.append(f"- **Tools:** {', '.join(_real_tools)}")
    if skill_names:
        lines.append(f"- **Skills:** {', '.join(skill_names)}")
    lines.append("\nDeploy to save, or describe what to change.")
    ai_msg = "\n".join(lines)
    session.messages.append({"role": "assistant", "content": ai_msg})
    yield _sse({
        "type": "message",
        "text": ai_msg,
        "stage": "confirm",
        "data": {"assembled": assembled},
    })


async def _build_and_stream_skill(session):
    """Run the skill blueprint → bundle → assemble pipeline for ``session``.

    Async generator yielding SSE frames (progress ``thinking`` events plus the
    final ``message`` event). Mutates ``session`` in place: sets
    ``session.blueprint``, ``session.bundle_files``, ``session.content``,
    ``session.assembled`` and advances ``session.stage`` to ``"confirm"``.
    Extracted from the inline ``/skill-factory/chat`` handler so both the
    first-generation path and the post-``suggest_existing`` path share one
    implementation.
    """
    _gen_t0 = time.perf_counter()
    yield _sse({"type": "thinking", "text": "Designing your skill blueprint…"})
    session.blueprint = await SkillBlueprintGenerator().generate(session.requirements)

    # Most skills are LLM-native text work and need no bundled files; the
    # blueprint's needs_bundle flag gates the extra 4096-token bundle-decider
    # call so the common path is just a single draft generation (like the
    # agent factory).
    if session.blueprint.get("needs_bundle"):
        yield _sse({"type": "thinking", "text": "Deciding which scripts/references this skill should ship with…"})
    yield _sse({"type": "thinking", "text": "Writing skill documentation…"})
    session.bundle_files, initial_content = await _draft_and_bundle(session.blueprint)
    if session.bundle_files:
        bundle_names = ", ".join(f["rel_path"] for f in session.bundle_files)
        yield _sse({"type": "thinking", "text": f"Bundled {len(session.bundle_files)} file(s): {bundle_names}"})

    session.content = initial_content

    # Deterministic, free quality summary (lint only). The LLM critique/
    # regenerate loop was removed to cut ~10-18 serial LLM round-trips that
    # dominated create latency; lint catches the remaining structural issues
    # without any network calls.
    quality_summary = _lint_summary(initial_content)

    logger.info(f"[AGENT] skill_factory: generate phase took {time.perf_counter() - _gen_t0}s (needs_bundle={bool(session.blueprint.get('needs_bundle'))}, {len(session.bundle_files or [])} bundled file(s))")

    assembled = SkillAssembler().assemble(
        session.blueprint,
        session.content,
        bundle_files=session.bundle_files,
        quality=quality_summary,
    )
    session.assembled = assembled
    session.stage = "confirm"

    quality_line = _quality_line(quality_summary)

    bundle_line = ""
    if session.bundle_files:
        bundle_line = "\n\n**Bundled files:** " + ", ".join(
            f"`{f['rel_path']}`" for f in session.bundle_files
        )

    summary = (
        f"✅ I've designed **{assembled['display_name']}**\n\n"
        f"**Description:** {assembled['description']}\n\n"
        f"**Category:** {assembled['category'].title()}"
        f"{bundle_line}"
        f"{quality_line}\n\n"
        f"Ready to add this skill to your catalog. Hit **Save Skill** to confirm, "
        f"or tell me what to change."
    )
    session.messages.append({"role": "assistant", "content": summary})
    yield _sse({
        "type": "message",
        "text": summary,
        "stage": "confirm",
        "data": {"assembled": assembled},
    })


# Prefix of the recommendation message written by ``_existing_match_message``.
# Used by ``_strip_match_messages`` to drop that message from history once the
# user moves on, so the LLM doesn't keep referencing it. Producer and consumer
# share this constant so re-wording the message can't silently break the strip.
_MATCH_MSG_PREFIX = "I found"


def _existing_match_message(kind_label: str, matches: list[dict]) -> str:
    """Human-readable recommendation text shown above the match cards."""
    if len(matches) == 1:
        top = matches[0]
        reason = (top.get("_match") or {}).get("reason") or ""
        line = f"{_MATCH_MSG_PREFIX} an existing {kind_label} that looks like a match"
        return (
            f"{line}: **{top.get('name')}**."
            + (f" {reason}" if reason else "")
            + "\n\nOpen it below, or choose **Continue building** to keep going."
        )
    names = ", ".join(f"**{m.get('name')}**" for m in matches)
    return (
        f"{_MATCH_MSG_PREFIX} {len(matches)} existing {kind_label}s that may already cover this: "
        f"{names}.\n\nOpen one below, or choose **Continue building** to keep going."
    )


def _strip_match_messages(messages: list[dict]) -> list[dict]:
    """Drop the existing-match recommendation from conversation history."""
    return [
        m for m in messages
        if not str(m.get("content", "")).startswith(_MATCH_MSG_PREFIX)
    ]


